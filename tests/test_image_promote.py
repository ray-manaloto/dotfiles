"""Tests for `promote`'s pre-retag staleness guard (image_promote, #1007).

`promote` retags a PR's `:pr-N` image as `:dev`/`:latest` after verifying the
retag itself was faithful, but never asked whether the SOURCE was current —
measured 2026-09-11: `:dev` carried pre-#1004 bytes for ~3h45m while `:pr-1004`
already had the fix. This module proves eligibility from the registry alone,
by comparing the candidate against the smoke-validated `:dev-<dev-hash>`
marker CI already pushes.

Layers, mirroring `test_image_manifest.py`'s structure for the sibling AC2
guard:

1. **Six control arms**, using the REAL `compute_repo_dev_hash` against a
   mutated repo fixture (only the registry read is faked) — stale, fresh,
   shape-agnostic, multi-arch, missing-marker, and a hard registry failure
   that must never be reinterpreted as either of the other two verdicts
   (`.claude/rules/probes-need-a-control-arm.md` rule 9).
2. **Wiring** — the CLI subcommand really reaches the verifier, and the
   parsed `ci.yml` proves the guard step runs BEFORE the retag step and that
   the retag step's `if:` actually depends on it — a perfect but unreachable
   verifier is exactly the failure mode this prevents.
"""

