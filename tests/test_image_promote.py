#: `published_targets()` is amd64-then-arm64 (`PUBLISHED_ARCHES`) — reused
#: directly rather than hand-rolled `PublishTarget`s, so these tests exercise
#: the SAME platform strings (`linux/amd64/v2`, `linux/arm64/v8`) the real
