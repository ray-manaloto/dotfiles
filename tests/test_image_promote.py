AMD64_TARGET, ARM64_TARGET = published_targets()

AMD64_STALE_DIGEST = "sha256:" + "a" * 64
AMD64_FRESH_DIGEST = "sha256:" + "b" * 64
ARM64_STALE_DIGEST = "sha256:" + "c" * 64
ARM64_FRESH_DIGEST = "sha256:" + "d" * 64


def _seed_repo(tmp_path: Path) -> Path:
    """A minimal repo tree `compute_repo_dev_hash` can read, no git needed.

    Copies `test_p2996_hash.py`'s `_seed_repo` fixture shape (same sentinel
    markers, same bake variables) — this file does not import that one
    since no test module here imports across test files, but the two must
    stay readable by the same hashing code, so the shape is deliberately
    identical.
    """
    (tmp_path / "docker-bake.hcl").write_text(
        'variable "BASE_IMAGE" { default = "ubuntu:26.04" }\n'
        'variable "PLATFORM" { default = "linux/amd64/v2" }\n'
        'variable "BUILDER_IMAGE" { default = "ubuntu:26.04@sha256:feedface" }\n'
        'variable "CLANG_P2996_REF" { default = "abc123" }\n'
        'target "dev" {\n'
        '  target = "devcontainer"\n'
        "  args = {\n"
        '    DEVCONTAINER_USER = "devcontainer"\n'
        "  }\n"
        "}\n",
    )
    devcontainer = tmp_path / ".devcontainer"
    devcontainer.mkdir()
    (devcontainer / "Dockerfile").write_text(
        textwrap.dedent(f"""\
        FROM ubuntu:26.04
        {BASE_SECTION_BEGIN}
        RUN apt-get update
        {BASE_SECTION_END}

        {P2996_SECTION_BEGIN}
        RUN cmake --build .
        {P2996_SECTION_END}

        FROM devcontainer-base AS devcontainer
        RUN echo final-stage
        """)
    )
    (devcontainer / "mise-system.lock").write_text(
        "# @generated by `mise lock`\n"
        '[[tools."conda:cmake"]]\nversion = "4.3.2"\nbackend = "conda:cmake"\n',
    )
    (devcontainer / "mise-system.toml").write_text(
        '[tools]\n"conda:cmake" = "latest"\n\n[settings]\nexperimental = true\n',
    )
    (tmp_path / "hk-common.pkl").write_text("hygiene = new {}\n")
    (tmp_path / "hk-image.pkl").write_text('amends "Config.pkl"\n')
    (devcontainer / "mise-runtime.toml").write_text('[tools]\nbats = "latest"\n')
    (devcontainer / "mise-runtime.lock").write_text(
        '[[tools.bats]]\nversion = "1.12.0"\n'
    )
    shared_dir = tmp_path / ".config" / "mise" / "conf.d"
    shared_dir.mkdir(parents=True)
    (shared_dir / "shared.toml").write_text('[tools]\nhk = "1.46.0"\n')
    return tmp_path


def _set_shared_toml(repo: Path, content: str) -> None:
    (repo / ".config" / "mise" / "conf.d" / "shared.toml").write_text(content)


@pytest.fixture
def repo(tmp_path: Path) -> Path:
    return _seed_repo(tmp_path)


def _index(*entries: dict[str, object]) -> str:
    return json.dumps(
        {
            "mediaType": "application/vnd.oci.image.index.v1+json",
            "manifests": list(entries),
        }
    )


def _entry(digest: str, arch: str, *, os_name: str = "linux") -> dict[str, object]:
    return {"digest": digest, "platform": {"architecture": arch, "os": os_name}}


def _inspector(
    raw: Mapping[str, str | BaseException],
    *,
    image_config: Mapping[str, str] | None = None,
    manifest_digest: Mapping[str, str] | None = None,
) -> Inspector:
    """A fake registry.

    Only `.raw` is populated unless a test needs the bare-manifest path —
    matching `test_image_manifest.py`'s `_inspector`.
    """

    def _raw(ref: str) -> str:
        value = raw[ref]
        if isinstance(value, BaseException):
            raise value
        return value

    def _missing(kind: str) -> Callable[[str], str]:
        def _raise(ref: str) -> str:
            msg = f"the promote guard consulted {kind} for {ref}; it must not"
            raise AssertionError(msg)

        return _raise

    return Inspector(
        raw=_raw,
        image_config=(
            (lambda ref: image_config[ref])
            if image_config is not None
            else _missing("{{json .Image}}")
        ),
        manifest_digest=(
            (lambda ref: manifest_digest[ref])
            if manifest_digest is not None
            else _missing("{{.Manifest.Digest}}")
        ),
    )


