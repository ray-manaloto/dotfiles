def test_stale_candidate_is_rejected(repo: Path) -> None:
    """A candidate built before a later commit's marker must never retag."""
    _set_shared_toml(repo, '[tools]\ncodex = "0.152.1"\n')
    stale_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)

    _set_shared_toml(repo, '[tools]\ncodex = "0.154.0"\nminimum_release_age = "0s"\n')
    fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    assert fresh_hash != stale_hash, "the fixture must genuinely differ"

    fresh_marker = marker_ref(IMAGE, fresh_hash)
    raw: dict[str, str | BaseException] = {
        CANDIDATE_REF: _index(_entry(AMD64_STALE_DIGEST, "amd64")),
        fresh_marker: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
    }
    verdict = check_promote_eligibility(
        repo_root=repo,
        candidate_ref=CANDIDATE_REF,
        inspector=_inspector(raw),
        targets=(AMD64_TARGET,),
    )
    assert not verdict.eligible
    assert verdict.status == "stale"
    line = verdict.lines[0]
    assert "amd64" in line
    assert CANDIDATE_REF in line
    assert AMD64_STALE_DIGEST in line
    assert fresh_marker in line
    assert AMD64_FRESH_DIGEST in line
    assert fresh_hash in line


def test_fresh_candidate_is_eligible(repo: Path) -> None:
    """Passing control: change ONLY the candidate entry to the fresh digest."""
    fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    fresh_marker = marker_ref(IMAGE, fresh_hash)
    raw = {
        CANDIDATE_REF: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        fresh_marker: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
    }
    verdict = check_promote_eligibility(
        repo_root=repo,
        candidate_ref=CANDIDATE_REF,
        inspector=_inspector(raw),
        targets=(AMD64_TARGET,),
    )
    assert verdict.eligible
    assert verdict.status == "eligible"


def test_bare_manifest_marker_still_resolves(repo: Path) -> None:
    """Shape control: the fresh marker is a bare manifest, not an index."""
    fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    fresh_marker = marker_ref(IMAGE, fresh_hash)
    bare_manifest = json.dumps(
        {
            "mediaType": "application/vnd.oci.image.manifest.v1+json",
            "config": {"digest": "sha256:" + "e" * 64},
            "layers": [],
        }
    )
    raw = {
        CANDIDATE_REF: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        fresh_marker: bare_manifest,
    }
    verdict = check_promote_eligibility(
        repo_root=repo,
        candidate_ref=CANDIDATE_REF,
        inspector=_inspector(
            raw,
            image_config={
                fresh_marker: json.dumps({"architecture": "amd64", "os": "linux"})
            },
            manifest_digest={fresh_marker: AMD64_FRESH_DIGEST},
        ),
        targets=(AMD64_TARGET,),
    )
    assert verdict.eligible


def test_multi_arch_one_stale_arch_rejects_the_whole_candidate(repo: Path) -> None:
    """amd64 matches, arm64 is stale — the WHOLE candidate must be rejected."""
    amd64_fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    arm64_fresh_hash = compute_repo_dev_hash(repo, platform=ARM64_TARGET.platform)
    assert amd64_fresh_hash != arm64_fresh_hash, "platform must move the hash"

    amd64_marker = marker_ref(IMAGE, amd64_fresh_hash)
    arm64_marker = marker_ref(IMAGE, arm64_fresh_hash)
    raw = {
        CANDIDATE_REF: _index(
            _entry(AMD64_FRESH_DIGEST, "amd64"),
            # arm64 candidate does NOT match its own marker below.
            _entry(ARM64_STALE_DIGEST, "arm64"),
        ),
        amd64_marker: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        arm64_marker: _index(_entry(ARM64_FRESH_DIGEST, "arm64")),
    }
    verdict = check_promote_eligibility(
        repo_root=repo,
        candidate_ref=CANDIDATE_REF,
        inspector=_inspector(raw),
        targets=(AMD64_TARGET, ARM64_TARGET),
    )
    assert not verdict.eligible
    assert verdict.status == "stale"
    assert any("arm64" in line for line in verdict.lines)


def test_missing_marker_is_unprovable_never_current(repo: Path) -> None:
    """An absent marker must classify as UNPROVABLE, never as eligible."""
    fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    fresh_marker = marker_ref(IMAGE, fresh_hash)
    raw: dict[str, str | BaseException] = {
        CANDIDATE_REF: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        fresh_marker: subprocess.CalledProcessError(
            1, ["docker", "buildx", "imagetools", "inspect"], stderr="manifest unknown"
        ),
    }
    verdict = check_promote_eligibility(
        repo_root=repo,
        candidate_ref=CANDIDATE_REF,
        inspector=_inspector(raw),
        targets=(AMD64_TARGET,),
    )
    assert not verdict.eligible
    assert verdict.status == "unprovable"
    assert fresh_marker in verdict.lines[0]


def test_registry_auth_failure_is_a_hard_failure_not_a_verdict(repo: Path) -> None:
    """An auth/network error must propagate — never read as stale or missing."""
    fresh_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    fresh_marker = marker_ref(IMAGE, fresh_hash)
    raw: dict[str, str | BaseException] = {
        CANDIDATE_REF: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        fresh_marker: subprocess.CalledProcessError(
            1,
            ["docker", "buildx", "imagetools", "inspect"],
            stderr="unauthorized: authentication required",
        ),
    }
    with pytest.raises(subprocess.CalledProcessError):
        check_promote_eligibility(
            repo_root=repo,
            candidate_ref=CANDIDATE_REF,
            inspector=_inspector(raw),
            targets=(AMD64_TARGET,),
        )


