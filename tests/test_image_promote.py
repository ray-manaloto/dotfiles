def test_cli_parses_and_routes_verify_promote_eligibility() -> None:
    parser = setup_parser()
    args = parser.parse_args(
        ["image", "verify-promote-eligibility", "--image-ref", CANDIDATE_REF]
    )
    assert args.image_command == "verify-promote-eligibility"
    assert args.image_ref == CANDIDATE_REF


def test_public_cli_executes_the_verifier(
    monkeypatch: pytest.MonkeyPatch,
    capsys: pytest.CaptureFixture[str],
    repo: Path,
) -> None:
    """Both CLI dispatch layers really reach `check_promote_eligibility`.

    Exercises the CLI's real default (`targets=None` -> `published_targets()`
    -> BOTH architectures), so this is the one test that is not narrowed to a
    single `targets=` override.
    """
    monkeypatch.setattr("dotfiles_setup.image._project_root", lambda: repo)
    amd64_hash = compute_repo_dev_hash(repo, platform=AMD64_TARGET.platform)
    arm64_hash = compute_repo_dev_hash(repo, platform=ARM64_TARGET.platform)
    amd64_marker = marker_ref(IMAGE, amd64_hash)
    arm64_marker = marker_ref(IMAGE, arm64_hash)
    raw = {
        CANDIDATE_REF: _index(
            _entry(AMD64_FRESH_DIGEST, "amd64"), _entry(ARM64_FRESH_DIGEST, "arm64")
        ),
        amd64_marker: _index(_entry(AMD64_FRESH_DIGEST, "amd64")),
        arm64_marker: _index(_entry(ARM64_FRESH_DIGEST, "arm64")),
    }
    monkeypatch.setattr(
        "dotfiles_setup.image.docker_inspector", lambda: _inspector(raw)
    )
    args = setup_parser().parse_args(
        ["image", "verify-promote-eligibility", "--image-ref", CANDIDATE_REF]
    )

    with pytest.raises(SystemExit) as exit_info:
        handle_image(args)

    assert exit_info.value.code == 0
    out = capsys.readouterr().out
    assert "eligible=true" in out
    assert "status=eligible" in out


def _promote_steps() -> list[dict]:
    workflow = yaml.safe_load((REPO_ROOT / ".github/workflows/ci.yml").read_text())
    return workflow["jobs"]["promote"]["steps"]


def test_eligibility_step_precedes_and_gates_the_retag_step() -> None:
    """A perfect verifier nobody calls, or a retag that ignores it, is a no-op."""
    steps = _promote_steps()
    names = [step.get("name", "") for step in steps]
    eligibility_index = next(
        i for i, name in enumerate(names) if "content-current" in name
    )
    retag_name = "Retag PR image as :dev and :latest"
    retag_index = next(i for i, name in enumerate(names) if name == retag_name)
    assert eligibility_index < retag_index, (
        "the staleness guard must run BEFORE the retag step"
    )

    eligibility_step = steps[eligibility_index]
    assert eligibility_step["id"] == "eligibility"
    assert "dotfiles-setup image verify-promote-eligibility" in eligibility_step["run"]

    retag_step = steps[retag_index]
    assert "steps.eligibility.outputs.eligible == 'true'" in retag_step["if"]
