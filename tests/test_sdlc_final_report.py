def _attested_records(*visible_finals: str) -> list[dict[str, Any]]:
    """Supply independent native raw/rendered boundaries for each final."""
    records = _records(*visible_finals)
    finals = records[2:-1]
    records = records[:2]
    for index, final in enumerate(finals):
        message_id = f"msg_observed_{index}"
        payload = final["payload"]
        assert isinstance(payload, dict)
        payload["id"] = message_id
        payload["content"] = [
            {"type": "output_text", "text": visible_finals[index] + _CITATION}
        ]
        records.extend(
            [
                _event(
                    "item_completed",
                    thread_id=_PARENT,
                    item={
                        "type": "AgentMessage",
                        "id": message_id,
                        "phase": "final_answer",
                        "content": [{"type": "Text", "text": visible_finals[index]}],
                        "memory_citation": {
                            "entries": [
                                {
                                    "path": "MEMORY.md",
                                    "lineStart": 12,
                                    "lineEnd": 13,
                                    "note": "retained source evidence",
                                }
                            ],
                            "rolloutIds": ["01a0a88c-674f-7bc3-bd32-923ec941d2e6"],
                        },
                    },
                ),
                final,
            ]
        )
    records.append(_event("task_complete", last_agent_message=visible_finals[-1]))
    return records


def _select(tmp_path: Path, captured: str) -> sdlc_final_report._FinalSelection:
    """Exercise only the public selector over an isolated transcript."""
    return sdlc_final_report.select_final_report(
        captured,
        parent_id=_PARENT,
        sessions_root=tmp_path,
        started_at=_START,
        finished_at=_FINISH,
    )


@pytest.mark.parametrize("earlier", [False, True])
def test_each_citation_final_binds_its_own_rendered_message(
    tmp_path: Path, *, earlier: bool
) -> None:
    """Earlier rendered text differs from latest; borrowing latest evidence fails."""
    records = (
        _attested_records(_ROSTER, _RECEIPT) if earlier else _attested_records(_ROSTER)
    )
    captured = _RECEIPT if earlier else _ROSTER
    _source(tmp_path, records)
    selected = _select(tmp_path, captured)
    assert selected.self_report.available is True
    assert selected.reason == (
        "prior-final-absence" if earlier else "latest-native-declaration"
    )
    assert selected.report_text == _ROSTER + _CITATION
    assert (
        selected.selected_hash
        == hashlib.sha256((_ROSTER + _CITATION).encode()).hexdigest()
    )
    assert (
        selected.captured_hash == hashlib.sha256(captured.rstrip().encode()).hexdigest()
    )
    assert selected.terminal_hash == selected.captured_hash
    assert selected.latest_hash != selected.terminal_hash
    provenance = sdlc_final_report.render_provenance(
        selected,
        identity=("citation-replay", _PARENT),
        captured_path=tmp_path / "capture.md",
        interval=(_START, _FINISH),
        participation_consistent=True,
    )
    assert "display transform: native-rendered-trailing-memory-citation" in provenance
    assert "retained source evidence" not in provenance
    assert "MEMORY.md" not in provenance
    records.pop(2)
    _source(tmp_path, records)
    refused = _select(tmp_path, captured)
    assert refused.self_report.available is False
    assert "rendered attestation" in refused.error


