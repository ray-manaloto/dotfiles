def _event(kind: str, **payload: object) -> dict[str, object]:
    """Build native event boundary input, independently of selector internals."""
    return {
        "timestamp": _TIMESTAMP,
        "type": "event_msg",
        "payload": {"type": kind, "turn_id": _TURN, **payload},
    }


def _final(text: str) -> dict[str, object]:
    """Build the modern final shape verified against actual native evidence."""
    return {
        "timestamp": _TIMESTAMP,
        "type": "response_item",
        "payload": {
            "type": "message",
            "role": "assistant",
            "phase": "final_answer",
            "content": [{"type": "output_text", "text": text}],
            "internal_chat_message_metadata_passthrough": {"turn_id": _TURN},
        },
    }


def _records(*finals: str) -> list[dict[str, object]]:
    """Return a whole bounded parent turn, with matching terminal output."""
    return [
        {"timestamp": _TIMESTAMP, "type": "session_meta", "payload": {"id": _PARENT}},
        _event("task_started", root_turn_id=_TURN),
        *(_final(text) for text in finals),
        _event("task_complete", last_agent_message=finals[-1]),
    ]


def _source(tmp_path: Path, records: list[dict[str, object]]) -> Path:
    """Write an isolated native parent through the project's codec."""
    path = tmp_path / f"rollout-parent-{_PARENT}.jsonl"
    path.write_bytes(b"".join(codec.encode(record) + b"\n" for record in records))
    return path


